/**
 * A `gog` wrapper that picks the relay token for the account each call names
 * (card #271).
 *
 * gog takes a single access token from GOG_ACCESS_TOKEN and then uses it for
 * every call, whatever --account says. With several relay-connected Gmail
 * accounts, or relay accounts beside gog's own sign-ins, one global token
 * would send every call to one mailbox. So the keeper puts the live tokens in
 * GOG_RELAY_TOKENS ({account: token}) and this wrapper, first on PATH and
 * returned by resolveGogBin, runs the real gog with:
 *
 *   - --account / -a / GOG_ACCOUNT naming a relay account: that account's token
 *   - naming any other account: no token, so gog uses its own stored sign-in
 *   - naming none: the relay account when it is the only one and gog has no
 *     sign-ins of its own; with several, a short error asking for --account
 *
 * `gog auth list` also lists the relay accounts, so the agent and the
 * discovery code see every account the box can reach.
 *
 * The wrapper is generated at startup into the store, not shipped: it bakes in
 * this box's node and real gog paths. Not installed on Windows (no shebangs);
 * the keeper falls back to the single-token behaviour there.
 */
import { chmodSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { delimiter, isAbsolute, join } from 'node:path'
import { RELAY_TOKENS_ENV } from './gmail-token.js'

/** Commands that never call a Google API, so they need no account. */
const NO_ACCOUNT = ['auth', 'version', 'help', 'completion', 'config', 'schema']

export function shimSource(realGog: string, nodePath: string): string {
  return `#!${nodePath}
'use strict'
// Generated by Havn (src/connect/gog-shim.ts). Picks the relay token for the
// account each gog call names. Rewritten at every start; do not edit.
const { spawnSync } = require('node:child_process')
const REAL = ${JSON.stringify(realGog)}
const NO_ACCOUNT = ${JSON.stringify(NO_ACCOUNT)}
const args = process.argv.slice(2)
const env = { ...process.env }
delete env.GOG_ACCESS_TOKEN
let tokens = {}
try { tokens = JSON.parse(env.${RELAY_TOKENS_ENV} || '{}') || {} } catch {}
delete env.${RELAY_TOKENS_ENV}
const relay = Object.keys(tokens)
const lc = (s) => String(s).trim().toLowerCase()
const find = (want) => relay.find((a) => lc(a) === lc(want))

function named() {
  for (let i = 0; i < args.length; i++) {
    const a = args[i]
    if (a === '--') break
    if (a === '--account' || a === '-a') return args[i + 1]
    if (a.startsWith('--account=')) return a.slice('--account='.length)
    if (a.startsWith('-a') && !a.startsWith('--') && a.length > 2) return a.slice(2).replace(/^=/, '')
  }
  return env.GOG_ACCOUNT
}

function run(e) {
  const r = spawnSync(REAL, args, { stdio: 'inherit', env: e })
  if (r.error) { process.stderr.write('gog: ' + r.error.message + '\\n'); process.exit(127) }
  process.exit(r.status === null ? 1 : r.status)
}

function ownAccounts() {
  const r = spawnSync(REAL, ['auth', 'list', '--plain'], { env, encoding: 'utf8' })
  return r.status === 0 ? String(r.stdout).split('\\n').filter((l) => /^[^\\s@]+@[^\\s@]+\\t/.test(l)).length : 0
}

const positional = args.filter((a) => !a.startsWith('-'))
const want = named()

if (relay.length && positional[0] === 'auth' && positional[1] === 'list' && !args.some((a) => a === '--json' || a === '-j')) {
  const r = spawnSync(REAL, args, { stdio: ['inherit', 'pipe', 'inherit'], env, encoding: 'utf8' })
  const out = r.status === 0 ? String(r.stdout) : ''
  process.stdout.write(out)
  const seen = out.toLowerCase()
  for (const a of relay) if (!seen.includes(lc(a))) process.stdout.write(a + '\\thavn-connect\\tcalendar,gmail\\trelay\\n')
  process.exit(0)
}

if (want && lc(want) !== 'auto') {
  const a = find(want)
  if (a) env.GOG_ACCESS_TOKEN = tokens[a]
  run(env)
}

if (relay.length && positional.length && !NO_ACCOUNT.includes(positional[0]) && ownAccounts() === 0) {
  if (relay.length === 1) env.GOG_ACCESS_TOKEN = tokens[relay[0]]
  else {
    process.stderr.write('Several Google accounts are connected (' + relay.join(', ') + '). Name one with --account.\\n')
    process.exit(2)
  }
}
run(env)
`
}

/** The real gog: an absolute path as given, or the bare name looked up on PATH. */
export function resolveReal(bin: string, path: string, exists: (p: string) => boolean = existsSync): string | undefined {
  if (isAbsolute(bin)) return exists(bin) ? bin : undefined
  for (const dir of path.split(delimiter)) {
    if (!dir) continue
    const p = join(dir, bin)
    if (exists(p)) return p
  }
  return undefined
}

/**
 * Write the wrapper into dir as `gog` (with a package.json so node reads it as
 * CommonJS) and return its path, or undefined where it cannot run.
 */
export function installGogShim(dir: string, realGog: string, nodePath: string, platform: string = process.platform): string | undefined {
  if (platform === 'win32') return undefined
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  writeFileSync(join(dir, 'package.json'), '{"type":"commonjs"}\n')
  const path = join(dir, 'gog')
  writeFileSync(path, shimSource(realGog, nodePath), { mode: 0o700 })
  chmodSync(path, 0o700)
  return path
}
